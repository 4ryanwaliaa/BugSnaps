const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
function load(file, dependencies = {}) {
  const code = ts.transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const mod = { exports: {} };
  vm.runInNewContext(code, { module: mod, exports: mod.exports, require: name => { if (!dependencies[name]) throw Error(`Unexpected dependency ${name}`); return dependencies[name]; }, Date, Number, Object, Math });
  return mod.exports;
}
const freshness = load("lib/endpointradar/freshness.ts");
const { overdueAfterMs } = freshness;
const { markMissing } = load("lib/endpointradar/watchdog.ts", { "./freshness": freshness });
const minute = 60_000;
assert.equal(overdueAfterMs(15), 46 * minute, "15-minute schedules allow polling and scan grace");
assert.equal(overdueAfterMs(30), 61 * minute);
assert.equal(overdueAfterMs(31), 62 * minute, "boundary where both rules agree");
assert.equal(overdueAfterMs(60), 120 * minute, "long intervals use twice the schedule");
assert.equal(overdueAfterMs(10080), 20160 * minute);
for (const invalid of [null, undefined, NaN, Infinity, -1, 14, 15.5, 10081, "15"]) assert.equal(overdueAfterMs(invalid), null);
const last = Date.parse("2026-10-28T12:00:00.000Z");
const device = { enabled: true, intervalMinutes: 15, createdAt: new Date(last).toISOString(), lastSeenAt: new Date(last).toISOString(), scans: { previous: { value: 1 } } };
assert.equal(markMissing(device, last + 30 * minute), undefined, "ordinary second scheduled run must not be flagged");
assert.equal(markMissing(device, last + 46 * minute), undefined, "threshold is exclusive");
const missing = markMissing(device, last + 46 * minute + 1);
assert.equal(missing.alertMissingSince, device.lastSeenAt);
assert.equal(Object.keys(missing.alerts).length, 1);
assert.equal(missing.scans.previous.value, 1);
assert.equal(markMissing(missing, last + 47 * minute), undefined, "retries must not duplicate an outage");
assert.equal(markMissing({ ...device, enabled: false }, last + 60 * minute), undefined);
assert.equal(markMissing({ ...device, intervalMinutes: 15.5 }, last + 60 * minute), undefined);
assert.equal(markMissing({ ...device, lastSeenAt: "bad date" }, last + 60 * minute), undefined);
const recovered = { ...missing, lastSeenAt: new Date(last + 60 * minute).toISOString(), alertMissingSince: null };
assert.equal(Object.keys(markMissing(recovered, last + 107 * minute).alerts).length, 2, "a later outage is a separate alert");
assert.equal(markMissing(null, last), null);
console.log("PASS freshness grace boundaries, watchdog outage, deduplication, recovery and invalid-state checks");
