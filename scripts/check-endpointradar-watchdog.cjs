const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const code = ts.transpileModule(fs.readFileSync("lib/endpointradar/watchdog.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const mod = { exports: {} }; vm.runInNewContext(code, { module: mod, exports: mod.exports, Date, Number, Object });
const { markMissing } = mod.exports;
const at = Date.parse("2026-10-28T12:00:00.000Z");
const device = { enabled: true, intervalMinutes: 30, createdAt: "2026-10-28T10:00:00.000Z", lastSeenAt: "2026-10-28T10:00:00.000Z", scans: { previous: { value: 1 } } };
const missing = markMissing(device, at);
assert.equal(missing.alertMissingSince, device.lastSeenAt);
assert.equal(Object.keys(missing.alerts).length, 1);
assert.equal(missing.scans.previous.value, 1);
assert.equal(markMissing(missing, at + 60000), undefined, "retries must not duplicate an outage");
assert.equal(markMissing({ ...device, enabled: false }, at), undefined);
assert.equal(markMissing({ ...device, lastSeenAt: "2026-10-28T11:30:00.000Z" }, at), undefined);
assert.equal(markMissing({ ...device, lastSeenAt: "bad date" }, at), undefined);
const recovered = { ...missing, lastSeenAt: "2026-10-28T12:00:00.000Z", alertMissingSince: null };
assert.equal(Object.keys(markMissing(recovered, at + 7200000).alerts).length, 2, "a later outage is a separate alert");
assert.equal(markMissing(null, at), null);
console.log("PASS watchdog outage, deduplication, recovery and invalid-state checks");
